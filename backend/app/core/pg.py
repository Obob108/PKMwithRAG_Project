EVENTS_CHANNEL = "pkm_events"


def is_postgres_url(target) -> bool:
    return str(target).startswith(("postgresql://", "postgres://"))


def _driver():
    import psycopg  # nap tre: chay voi SQLite khong can cai psycopg

    return psycopg


def translate(sql: str) -> str:
    """Doi dau ? (ngoai chuoi '...' va dinh danh "...") thanh %s; % thuong thanh %%."""
    out: list[str] = []
    quote = None
    for ch in sql:
        if quote:
            out.append("%%" if ch == "%" else ch)
            if ch == quote:
                quote = None
        elif ch in ("'", '"'):
            quote = ch
            out.append(ch)
        elif ch == "?":
            out.append("%s")
        elif ch == "%":
            out.append("%%")
        else:
            out.append(ch)
    return "".join(out)


def _plain(v):
    if isinstance(v, dt.datetime):
        if v.tzinfo is not None:
            v = v.astimezone(dt.timezone.utc)
        return v.strftime("%Y-%m-%d %H:%M:%S")
    return v


class Row(tuple):
    """Dong ket qua doc duoc ca row["ten_cot"] lan row[0], giong sqlite3.Row."""

    __slots__ = ()
    _index: dict  # gan theo tung lop con (moi tap cot mot lop)

    def __getitem__(self, key):
        if isinstance(key, str):
            return tuple.__getitem__(self, self._index[key])
        return tuple.__getitem__(self, key)

    def keys(self):
        return list(self._index)


_row_classes: dict[tuple, type] = {}


def _row_class(names: tuple) -> type:
    cls = _row_classes.get(names)
    if cls is None:
        cls = type("Row", (Row,), {"__slots__": (), "_index": {n: i for i, n in enumerate(names)}})
        _row_classes[names] = cls
    return cls


class PgCursor:
    def __init__(self, cur):
        self._cur = cur
        desc = cur.description
        self._cls = _row_class(tuple(c.name for c in desc)) if desc else None

    @property
    def rowcount(self) -> int:
        return self._cur.rowcount

    def _wrap(self, r):
        return None if r is None else self._cls(_plain(v) for v in r)

    def fetchone(self):
        return self._wrap(self._cur.fetchone()) if self._cls else None

    def fetchall(self):
        return [self._wrap(r) for r in self._cur.fetchall()] if self._cls else []

    def __iter__(self):
        return iter(self.fetchall())


class PgConnection:
    """Boc ket noi psycopg: cung cac ham ma ma nguon dung voi sqlite3 (execute, executescript, commit...)."""

    is_postgres = True

    def __init__(self, raw):
        self.raw = raw

    def execute(self, sql: str, params=()):
        params = list(params) if params is not None else []
        if not params:  # khong co tham so: psycopg khong xu ly %, gui nguyen cau lenh
            return PgCursor(self.raw.execute(sql))
        return PgCursor(self.raw.execute(translate(sql), params))

    def executescript(self, sql: str) -> None:
        self.raw.execute(sql)

    def commit(self) -> None:
        self.raw.commit()

    def rollback(self) -> None:
        self.raw.rollback()

    def close(self) -> None:
        self.raw.close()

    @property
    def closed(self) -> bool:
        return bool(self.raw.closed)


def connect_pg(url: str, autocommit: bool = False) -> PgConnection:
    raw = _driver().connect(url, autocommit=autocommit)
    raw.execute("SET TIME ZONE 'UTC'")
    if not autocommit:
        raw.commit()
    return PgConnection(raw)


def init_pg(conn: PgConnection) -> None:
    """Tao schema neu chua co (idempotent). Khoa advisory de nhieu tien trinh khoi dong cung luc khong dam nhau."""
    conn.execute("SELECT pg_advisory_xact_lock(424242)")
    conn.executescript(SCHEMA_PG)
    if conn.execute("SELECT version FROM schema_meta").fetchone() is None:
        conn.execute("INSERT INTO schema_meta(version) VALUES (?)", (SCHEMA_VERSION,))
    conn.commit()


class PgPool:
    """Connection pool don gian, an toan da luong: muon / tra ket noi thay vi mo moi moi lan."""

    def __init__(self, url: str, max_size: int = 10, timeout: float = 30.0):
        self.url, self.max_size, self.timeout = url, max_size, timeout
        self._idle: queue.LifoQueue[PgConnection] = queue.LifoQueue()
        self._lock = threading.Lock()
        self._opened = 0
        self._sem = threading.BoundedSemaphore(max_size)

    def _take(self) -> PgConnection:
        while True:
            try:
                conn = self._idle.get_nowait()
            except queue.Empty:
                with self._lock:
                    self._opened += 1
                try:
                    return connect_pg(self.url)
                except Exception:
                    with self._lock:
                        self._opened -= 1
                    raise
            if not conn.closed:
                return conn
            with self._lock:
                self._opened -= 1

    def _give_back(self, conn: PgConnection) -> None:
        try:
            if not conn.closed:
                conn.rollback()  # bo phan giao dich con do dang (request loi giua chung)
        except Exception:  # noqa: BLE001  ket noi hong: dong han
            try:
                conn.close()
            except Exception:  # noqa: BLE001
                pass
        if conn.closed:
            with self._lock:
                self._opened -= 1
        else:
            self._idle.put(conn)

    @contextmanager
    def connection(self):
        if not self._sem.acquire(timeout=self.timeout):
            raise TimeoutError(f"Het ket noi trong pool (toi da {self.max_size})")
        conn = None
        try:
            conn = self._take()
            yield conn
        finally:
            if conn is not None:
                self._give_back(conn)
            self._sem.release()

    @property
    def size(self) -> int:
        return self._opened

    def close(self) -> None:
        while True:
            try:
                conn = self._idle.get_nowait()
            except queue.Empty:
                break
            try:
                conn.close()
            except Exception:  # noqa: BLE001
                pass
            with self._lock:
                self._opened -= 1
